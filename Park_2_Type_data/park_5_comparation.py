a = 10
b = 10
# besar dari (>)
hasil = a > b 
print(f"Apakah hasil dari {a} lebih besar dari (>) {b} adalah : {hasil}")
# kecil dari (<)
hasil = a < b 
print(f"Apakah hasil dari {a} lebih kecil dari (<) {b} adalah : {hasil}")
# besar dari sama dengan (>=)
hasil = a >= b 
print(f"Apakah hasil dari {a} lebih besar dari sama dengan (>=) {b} adalah : {hasil}")
# kecil dari sama dengan (<=)
hasil = a <= b 
print(f"Apakah hasil dari {a} lebih kecil dari sama dengan (<=) {b} adalah : {hasil}")

c = "1"
d = 1
# sama dengan (==)
hasil = c == d 
print(f"Apakah hasil dari {c} sama dengan (==) {d} adalah : {hasil}")

f = True
# not (!=)
hasil = f != False
print(f"Apakah hasil dari {f} tidak sama dengan True adalah : {hasil}")


